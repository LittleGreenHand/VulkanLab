void VulkanRendererBase::windowResize()
{
	if (!m_init)
	{
		return;
	}
	m_init = false;
	resized = true;

	InitRenderResource();

	if ((m_renderWidth > 0.0f) && (m_renderHeiht > 0.0f)) {
		camera.updateAspectRatio((float)m_renderWidth / (float)m_renderHeiht);
	}
	resized = false;
	m_init = true;
}

void VulkanRendererBase::InitSurfaceKHR(VkSurfaceKHR surface)
{
	swapChain.InitSurfaceKHR(surface);
}

void VulkanRendererBase::createSwapChain()
{
	swapChain.create(m_framebufferWidth, m_framebufferHeiht, settings.vsync, settings.fullscreen);
	for (int i = 0; i < swapChain.swapChainImages.size(); i++)
		VulkanDebugUtils::SetObjectDebugName(VK_OBJECT_TYPE_IMAGE, (uint64_t)swapChain.swapChainImages[i].image, ("swapchainImage" + std::to_string(i)));
}
